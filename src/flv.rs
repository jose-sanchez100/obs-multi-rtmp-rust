//! Conversion of OBS encoded packets into FLV tag bodies.
//!
//! - H.264: OBS delivers Annex-B (start codes). RTMP/FLV requires AVCC (4-byte
//!   length prefix) and an `AVCDecoderConfigurationRecord` as the header.
//! - AAC: OBS delivers raw AAC; the extradata is the AudioSpecificConfig.

use crate::queue::{Kind, MediaPacket};
use bytes::Bytes;

/// Splits an Annex-B buffer into NALs (without start codes).
pub fn split_annexb(data: &[u8]) -> Vec<&[u8]> {
    let mut starts = Vec::new(); // (start code position, start code length)
    let mut i = 0;
    while i + 3 <= data.len() {
        if data[i] == 0 && data[i + 1] == 0 {
            if data[i + 2] == 1 {
                starts.push((i, 3));
                i += 3;
                continue;
            }
            if i + 4 <= data.len() && data[i + 2] == 0 && data[i + 3] == 1 {
                starts.push((i, 4));
                i += 4;
                continue;
            }
        }
        i += 1;
    }
    let mut out = Vec::with_capacity(starts.len());
    for (k, &(pos, len)) in starts.iter().enumerate() {
        let begin = pos + len;
        let mut end = starts.get(k + 1).map(|s| s.0).unwrap_or(data.len());
        // trailing padding zeros (trailing_zero_8bits)
        while end > begin && data[end - 1] == 0 && k + 1 == starts.len() {
            end -= 1;
        }
        if end > begin {
            out.push(&data[begin..end]);
        }
    }
    out
}

fn nal_type(n: &[u8]) -> u8 {
    n[0] & 0x1f
}

/// Annex-B -> AVCC, dropping SPS/PPS/AUD (they belong only in the sequence header).
/// Returns (data, contains_idr).
pub fn annexb_to_avcc(data: &[u8]) -> (Vec<u8>, bool) {
    let mut out = Vec::with_capacity(data.len() + 16);
    let mut idr = false;
    for nal in split_annexb(data) {
        match nal_type(nal) {
            7 | 8 | 9 => continue,
            5 => idr = true,
            _ => {}
        }
        out.extend_from_slice(&(nal.len() as u32).to_be_bytes());
        out.extend_from_slice(nal);
    }
    (out, idr)
}

/// Builds the AVCDecoderConfigurationRecord from SPS+PPS in Annex-B.
pub fn avc_config_record(extradata_annexb: &[u8]) -> Option<Vec<u8>> {
    let nals = split_annexb(extradata_annexb);
    let sps = nals.iter().find(|n| nal_type(n) == 7 && n.len() >= 4)?;
    let pps = nals.iter().find(|n| nal_type(n) == 8)?;
    let mut r = vec![1, sps[1], sps[2], sps[3], 0xFF, 0xE1];
    r.extend_from_slice(&(sps.len() as u16).to_be_bytes());
    r.extend_from_slice(sps);
    r.push(1);
    r.extend_from_slice(&(pps.len() as u16).to_be_bytes());
    r.extend_from_slice(pps);
    Some(r)
}

fn video_body(keyframe: bool, avc_packet_type: u8, comp_time: i32, payload: &[u8]) -> Bytes {
    let mut v = Vec::with_capacity(5 + payload.len());
    v.push(if keyframe { 0x17 } else { 0x27 });
    v.push(avc_packet_type);
    let ct = comp_time.clamp(-0x80_0000, 0x7f_ffff);
    v.extend_from_slice(&ct.to_be_bytes()[1..4]);
    v.extend_from_slice(payload);
    Bytes::from(v)
}

/// Video sequence header from Annex-B or from a ready-made AVC record.
pub fn video_header(extradata: &[u8]) -> Option<MediaPacket> {
    let data = if extradata.starts_with(&[1]) {
        // An AVC record already generated by libobs keeps the High profile extension.
        if extradata.len() < 11 || extradata[4] != 0xff {
            return None;
        }
        video_body(true, 0, 0, extradata)
    } else {
        video_body(true, 0, 0, &avc_config_record(extradata)?)
    };
    Some(MediaPacket { kind: Kind::Video, dts_ms: 0, keyframe: true, is_header: true, data })
}

/// Video frame. `None` if the packet contains no usable slices.
pub fn video_frame(dts_ms: i64, pts_ms: i64, annexb: &[u8]) -> Option<MediaPacket> {
    let (avcc, idr) = annexb_to_avcc(annexb);
    if avcc.is_empty() {
        return None;
    }
    let comp = (pts_ms - dts_ms) as i32;
    Some(MediaPacket {
        kind: Kind::Video,
        dts_ms: dts_ms.max(0) as u32,
        keyframe: idr,
        is_header: false,
        data: video_body(idr, 1, comp, &avcc),
    })
}

pub fn audio_header(audio_specific_config: &[u8]) -> MediaPacket {
    let mut v = vec![0xAF, 0];
    v.extend_from_slice(audio_specific_config);
    MediaPacket { kind: Kind::Audio, dts_ms: 0, keyframe: false, is_header: true, data: Bytes::from(v) }
}

pub fn audio_frame(dts_ms: i64, raw_aac: &[u8]) -> MediaPacket {
    let mut v = Vec::with_capacity(2 + raw_aac.len());
    v.extend_from_slice(&[0xAF, 1]);
    v.extend_from_slice(raw_aac);
    MediaPacket { kind: Kind::Audio, dts_ms: dts_ms.max(0) as u32, keyframe: false, is_header: false, data: Bytes::from(v) }
}

#[cfg(test)]
mod tests {
    use super::*;

    const SPS: [u8; 6] = [0x67, 0x64, 0x00, 0x1f, 0xac, 0xd9];
    const PPS: [u8; 4] = [0x68, 0xeb, 0xe3, 0xcb];

    fn annexb(nals: &[&[u8]], long_first: bool) -> Vec<u8> {
        let mut v = Vec::new();
        for (i, n) in nals.iter().enumerate() {
            if i == 0 && long_first {
                v.extend_from_slice(&[0, 0, 0, 1]);
            } else {
                v.extend_from_slice(&[0, 0, 1]);
            }
            v.extend_from_slice(n);
        }
        v
    }

    #[test]
    fn splits_mixed_start_codes() {
        let d = annexb(&[&SPS, &PPS, &[0x65, 1, 2, 3]], true);
        let n = split_annexb(&d);
        assert_eq!(n.len(), 3);
        assert_eq!(n[0], &SPS);
        assert_eq!(n[2], &[0x65, 1, 2, 3]);
    }

    #[test]
    fn config_record_layout() {
        let d = annexb(&[&SPS, &PPS], true);
        let r = avc_config_record(&d).unwrap();
        assert_eq!(&r[..6], &[1, 0x64, 0x00, 0x1f, 0xFF, 0xE1]);
        assert_eq!(u16::from_be_bytes([r[6], r[7]]) as usize, SPS.len());
        let p = 8 + SPS.len();
        assert_eq!(r[p], 1);
        assert_eq!(&r[p + 3..], &PPS);
        let h = video_header(&d).unwrap();
        assert!(h.is_header && h.data[0] == 0x17 && h.data[1] == 0);
    }

    #[test]
    fn preserves_the_high_profile_extension_in_encoder_config() {
        let annexb = annexb(&[&SPS, &PPS], true);
        let mut config = avc_config_record(&annexb).unwrap();
        config.extend_from_slice(&[0xfd, 0xf8, 0xf8, 0]);
        let header = video_header(&config).unwrap();
        assert_eq!(&header.data[..5], &[0x17, 0, 0, 0, 0]);
        assert_eq!(&header.data[5..], config);
    }

    #[test]
    fn idr_frame_strips_params_and_prefixes_lengths() {
        let idr = [0x65u8, 9, 9, 9, 9];
        let d = annexb(&[&[0x09, 0xf0], &SPS, &PPS, &idr], true);
        let f = video_frame(1000, 1066, &d).unwrap();
        assert!(f.keyframe);
        assert_eq!(f.dts_ms, 1000);
        assert_eq!(&f.data[..2], &[0x17, 1]);
        assert_eq!(&f.data[2..5], &[0, 0, 66]); // composition time
        assert_eq!(&f.data[5..9], &(idr.len() as u32).to_be_bytes());
        assert_eq!(&f.data[9..], &idr);
    }

    #[test]
    fn p_frame_and_negative_composition_time() {
        let p = [0x41u8, 1, 2];
        let f = video_frame(100, 90, &annexb(&[&p], false)).unwrap();
        assert!(!f.keyframe);
        assert_eq!(&f.data[..2], &[0x27, 1]);
        assert_eq!(&f.data[2..5], &[0xFF, 0xFF, 0xF6]); // -10
    }

    #[test]
    fn audio_tags() {
        let h = audio_header(&[0x12, 0x10]);
        assert!(h.is_header && &h.data[..] == &[0xAF, 0, 0x12, 0x10]);
        let f = audio_frame(5, &[1, 2, 3]);
        assert_eq!(&f.data[..], &[0xAF, 1, 1, 2, 3]);
    }
}
